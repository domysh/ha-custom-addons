#!/usr/bin/env bash
# Podman setup for the Fedora Podman Shell add-on.
# Sourced by entrypoint.sh; not meant to be executed on its own.
#
# The two things this file exists to get right:
#
#  1. Persistence. Podman's graph root goes on a mapped host path, so images,
#     containers and volumes survive an add-on update. The container's own
#     filesystem is thrown away every time the add-on is rebuilt.
#
#  2. A sane storage driver. This is a container inside a container, so the
#     usual assumption "overlay just works" does not hold: the add-on's own
#     root filesystem is already an overlay mount, and overlay-on-overlay is
#     not supported on Home Assistant OS (its kernel is built with
#     CONFIG_OVERLAY_FS_REDIRECT_DIR and CONFIG_OVERLAY_FS_METACOPY off).
#     What saves us is that the graph root is NOT on the container's overlay
#     rootfs but on a bind mount from the host's ext4 data partition, where a
#     plain overlay mount is fine. Rather than trusting that reasoning, the
#     code below actually performs an overlay mount on the real storage path
#     and looks at whether it worked.

# Podman's default network_config_dir (/etc/containers/networks) is inside the
# container, so any network created by the user would vanish on update. Kept
# under the graph root instead, together with everything else stateful.
readonly PODMAN_RUNROOT="/run/containers/storage"
# Not "podman": that name belongs to the network Podman creates for itself, and
# it is IPv4-only. See ensure_dualstack_default_network.
readonly PODMAN_DEFAULT_NETWORK="podman-dual"

# Attempts a real overlay mount on the given directory's filesystem.
# Returns 0 if the kernel accepts it, 1 otherwise. This is an empirical test on
# the exact filesystem Podman will use, which is the only trustworthy answer.
test_native_overlay() {
    local base="$1"
    local test_dir rc=1

    test_dir="$(mktemp -d "${base}/.overlay-probe.XXXXXX" 2>/dev/null)" || return 1
    mkdir -p "${test_dir}/lower" "${test_dir}/upper" "${test_dir}/work" "${test_dir}/merged"

    if mount -t overlay overlay \
        -o "lowerdir=${test_dir}/lower,upperdir=${test_dir}/upper,workdir=${test_dir}/work" \
        "${test_dir}/merged" 2>/dev/null
    then
        umount "${test_dir}/merged" 2>/dev/null || true
        rc=0
    fi

    rm -rf "${test_dir}"
    return "${rc}"
}

test_fuse_overlay() {
    command -v fuse-overlayfs >/dev/null 2>&1 || return 1
    # fuse-overlayfs needs the device node; on boards where fuse is a module
    # rather than built in, it may only appear after a modprobe (which is why
    # the add-on requests kernel_modules).
    [ -c /dev/fuse ] || modprobe fuse 2>/dev/null || true
    [ -c /dev/fuse ]
}

select_storage_driver() {
    local graphroot="$1"

    # Harmless if overlay is built in; needed if it is a module.
    modprobe overlay 2>/dev/null || true

    if test_native_overlay "${graphroot}"; then
        PODMAN_STORAGE_DRIVER="overlay"
        PODMAN_MOUNT_PROGRAM=""
        log "Storage driver: overlay (native kernel overlay works on ${graphroot})"
        return 0
    fi

    log "Native overlay is not usable on ${graphroot}, trying fuse-overlayfs"

    if test_fuse_overlay; then
        PODMAN_STORAGE_DRIVER="overlay"
        PODMAN_MOUNT_PROGRAM="/usr/bin/fuse-overlayfs"
        log "Storage driver: overlay via fuse-overlayfs (slower than native, but correct)"
        return 0
    fi

    # Podman's own fallback here would be vfs, which copies every layer in full
    # instead of stacking them. On a Raspberry Pi's SD card that means many
    # gigabytes wasted per image and painfully slow pulls - a broken setup that
    # looks like it works, which is worse than not starting.
    fatal \
        "No usable Podman storage driver: neither native overlay nor fuse-overlayfs works." \
        "Refusing to fall back to the 'vfs' driver, which would waste enormous" \
        "amounts of space and be extremely slow on SD-card storage." \
        "" \
        "Things to check:" \
        "  - Protection mode must be OFF for this add-on (Info tab), otherwise" \
        "    the Supervisor drops the device and capability grants it needs." \
        "  - 'podman_storage_path' must be on a mapped host path (currently:" \
        "    ${graphroot}); overlay cannot stack on the add-on's own overlay rootfs." \
        "  - For the fuse fallback, /dev/fuse must exist inside the add-on." \
        "    Check with: ls -l /dev/fuse"
}

write_storage_conf() {
    local graphroot="$1"

    mkdir -p /etc/containers
    {
        echo "# Generated by the Fedora Podman Shell add-on on every start."
        echo "[storage]"
        echo "driver = \"${PODMAN_STORAGE_DRIVER}\""
        echo "graphroot = \"${graphroot}\""
        # runroot holds runtime state only and must NOT be persistent: stale
        # entries from a previous boot would describe containers that no longer
        # exist. /run is a fresh tmpfs on every start, which is what we want.
        echo "runroot = \"${PODMAN_RUNROOT}\""
        echo
        echo "[storage.options]"
        if [ -n "${PODMAN_MOUNT_PROGRAM}" ]; then
            echo "mount_program = \"${PODMAN_MOUNT_PROGRAM}\""
        fi
        echo
        echo "[storage.options.overlay]"
        # The add-on's storage lives on the host data partition; containers
        # have no business creating device nodes there.
        echo "mountopt = \"nodev\""
    } > /etc/containers/storage.conf
}

write_containers_conf() {
    local graphroot="$1"

    mkdir -p /etc/containers
    cat > /etc/containers/containers.conf <<EOF
# Generated by the Fedora Podman Shell add-on on every start.

[containers]
# Containers started here get their own network namespace by default, even
# though the add-on itself runs with host networking. Inheriting host
# networking implicitly would put every container straight onto the host's
# stack, where it could collide with Home Assistant's own ports.
netns = "bridge"
# Podman decides its default log driver by reading /proc/1/comm and using
# journald when it finds "systemd" and a readable journal directory. This
# add-on shares the host PID namespace, so PID 1 *is* Home Assistant OS's
# systemd - while the journal socket it would write to lives in the host's
# mount namespace and is unreachable from here. Left to that detection, one
# stray /var/log/journal directory (the persistent /var layer is exactly the
# kind of place one appears in) is enough to switch the driver over and make 'podman logs'
# return nothing at all. k8s-file writes the log next to the container in the
# graph root, which is what 'podman logs' reads back.
# (No backticks in this heredoc: it is unquoted, so they would be executed.)
log_driver = "k8s-file"

[network]
network_backend = "netavark"
# netavark 2.x dropped its iptables driver: the choices are firewalld (not
# running here), nftables, or none. Naming it saves netavark a dbus probe for
# firewalld on every container start, and makes it explicit which of the host's
# two firewall views the container rules land in - see allow_podman_forwarding.
firewall_driver = "nftables"
# A dual-stack network created by the add-on, in place of Podman's own IPv4-only
# default. Without it, published ports answer on IPv4 and are invisible over
# IPv6. See ensure_dualstack_default_network.
default_network = "${PODMAN_DEFAULT_NETWORK}"
# Kept with the rest of the state so user-defined networks survive updates.
network_config_dir = "${graphroot}/networks"

[engine]
# "podman compose" is a thin wrapper that hands over to an external provider.
# Left to itself it picks the Docker Compose plugin if one is present, which
# then tries to reach a Docker-compatible API socket that nothing here serves:
#
#   failed to connect to the docker API at unix:///run/podman/podman.sock
#
# podman-compose needs no socket - it just calls podman - so it is named
# explicitly, which makes "podman compose" and "podman-compose" equivalent.
# (No backticks in this heredoc: it is unquoted, so they would be executed.)
compose_providers = ["podman-compose"]
# Suppresses the "Executing external compose provider" banner on every run.
compose_warning_logs = false
# There is no systemd in this container, so the systemd cgroup manager has
# nothing to talk to. cgroupfs writes the cgroup hierarchy directly.
cgroup_manager = "cgroupfs"
# journald is not running either; the file logger keeps events in the graph
# root instead of failing to connect to a socket on every operation.
events_logger = "file"
runtime = "crun"
static_dir = "${graphroot}/libpod"
volume_path = "${graphroot}/volumes"
tmp_dir = "/run/libpod"
EOF
}

write_registries_conf() {
    # Podman's own registry configuration, independent of whatever the host's
    # Docker is configured with. Without unqualified-search-registries, a
    # `podman pull nginx` fails instead of resolving to docker.io.
    mkdir -p /etc/containers
    cat > /etc/containers/registries.conf <<'EOF'
# Generated by the Fedora Podman Shell add-on on every start.
unqualified-search-registries = ["docker.io", "ghcr.io", "quay.io", "registry.fedoraproject.org"]

# "permissive" resolves a short name against the search list above without
# prompting. "enforcing" would ask which registry you meant on every ambiguous
# pull, which is safer but turns any non-interactive script into a hang.
short-name-mode = "permissive"
EOF
}

# The prefix check in validate_options only proves the path *looks* like a
# mapped one. It would still pass if the mount were not actually there - for
# instance on a Supervisor too old to know the `app_config` / `all_app_configs`
# map types this add-on declares, which would leave /config or /app_configs as
# an ordinary directory in the container's writable layer. Podman would then
# happily fill it and lose the lot on the next update. Comparing the device
# with the one backing / catches exactly that: a real mapped path is a bind
# mount from the host and always sits on a different device.
assert_path_is_persistent() {
    local graphroot="$1"
    local root_dev path_dev

    root_dev="$(stat -c '%d' / 2>/dev/null)" || return 0
    path_dev="$(stat -c '%d' "${graphroot}" 2>/dev/null)" || return 0

    if [ "${root_dev}" = "${path_dev}" ]; then
        fatal \
            "'podman_storage_path' (${graphroot}) is on the container's own filesystem," \
            "not on a mapped host path, despite looking like one." \
            "Everything stored there would be lost on the next add-on update." \
            "" \
            "The usual cause is a Supervisor older than 2026.07, which does not" \
            "know the 'app_config' / 'all_app_configs' map types this add-on" \
            "declares and therefore never created those mounts." \
            "Update Home Assistant, or point 'podman_storage_path' at /share instead."
    fi
}

# Docker mounts /sys/fs/cgroup read-only in every container that is not truly
# privileged, and the Supervisor never passes --privileged: `full_access` only
# adds device cgroup rules. Podman must create a cgroup for each container it
# starts, so without this it fails at the first `podman run` with:
#
#   Error: creating cgroup path /libpod_parent/<id>:
#   mkdir /sys/fs/cgroup/libpod_parent: read-only file system
#
# Remounting read-write is allowed because the add-on holds CAP_SYS_ADMIN in
# its own (non-user) mount namespace. With Docker's default private cgroup
# namespace this only affects the add-on's own cgroup subtree, not the host's.
configure_cgroups() {
    local cg=/sys/fs/cgroup

    if [ ! -d "${cg}" ]; then
        warn "${cg} does not exist; Podman will not be able to create cgroups."
        return 0
    fi

    if [ ! -w "${cg}" ]; then
        if mount -o remount,rw "${cg}" 2>/dev/null; then
            log "Remounted ${cg} read-write so Podman can create container cgroups"
        else
            warn "${cg} is read-only and could not be remounted read-write."
            warn "Podman will fail to start containers with a 'read-only file system'"
            warn "error when creating the cgroup path. This needs Protection mode OFF."
            warn "As a stop-gap you can run containers with: podman run --cgroups=disabled"
            return 0
        fi
    fi

    # cgroup v2 only. On v2 a controller can only be used by child cgroups if
    # the parent lists it in cgroup.subtree_control, and without that Podman
    # can create cgroups but cannot apply any memory/CPU limit to them.
    [ -r "${cg}/cgroup.controllers" ] || return 0

    # The "no internal processes" rule forbids enabling controllers for
    # children while the cgroup itself still holds processes - and ours all sit
    # in the container's cgroup root. They have to be moved into a child cgroup
    # first, and moving them is not a single pass: cgroup.procs is generated on
    # read, so the list shifts under the reader as PIDs leave it and one sweep
    # reliably leaves some behind. One straggler is enough to make every
    # delegation below fail with EBUSY.
    if [ -w "${cg}/cgroup.procs" ]; then
        mkdir -p "${cg}/addon" 2>/dev/null || true
        local sweep=0
        while [ "${sweep}" -lt 20 ]; do
            while read -r pid; do
                [ -n "${pid}" ] || continue
                echo "${pid}" > "${cg}/addon/cgroup.procs" 2>/dev/null || true
            done < "${cg}/cgroup.procs"
            # Not `[ -s ]`: kernel-generated files report a size of zero
            # whatever they contain.
            [ -n "$(cat "${cg}/cgroup.procs" 2>/dev/null)" ] || break
            sweep=$((sweep + 1))
        done
    fi

    # cgroup.controllers is a single line of space-separated names, so it is
    # read as words rather than lines.
    # Every controller listed here has to end up in cgroup.subtree_control,
    # not just the ones we care about: Podman reads this same file to decide
    # what to enable for each container, and writes the whole list into the
    # container's cgroup without checking what is actually delegated. One
    # missing controller therefore fails the container outright - and it fails
    # on the first name in this list, which is why the error usually says
    # "cpuset" whatever the real problem is.
    local controllers=() controller enabled=() failed=() err=""
    read -r -a controllers < "${cg}/cgroup.controllers" || true
    for controller in "${controllers[@]}"; do
        # EBUSY here is often transient - the kernel reports it while the
        # processes just moved out are still being accounted for - so a few
        # attempts are worth making. Podman's own code retries it a thousand
        # times for the same reason.
        err=""
        for _ in 1 2 3 4 5; do
            if err="$( { echo "+${controller}" > "${cg}/cgroup.subtree_control"; } 2>&1 )"; then
                err=""
                break
            fi
            case "${err}" in
                *"busy"* | *"Busy"*) sleep 0.2 ;;
                *) break ;;
            esac
        done

        if [ -z "${err}" ]; then
            enabled+=("${controller}")
        else
            # Kept and reported rather than swallowed: a controller that is
            # advertised here but not delegated is exactly what makes a
            # container fail later with
            #   enabling controller <name>: ... cgroup.subtree_control:
            #   no such file or directory
            # which names the container's own cgroup and gives no hint that the
            # cause is one level up, here.
            failed+=("${controller}")
            [ -n "${err}" ] && err="${err##*: }"
        fi
    done

    if [ "${#enabled[@]}" -gt 0 ]; then
        log "Delegated cgroup controllers to containers: ${enabled[*]}"
    fi

    if [ "${#failed[@]}" -gt 0 ]; then
        warn "These cgroup controllers could not be delegated: ${failed[*]}"
        [ -n "${err}" ] && warn "The kernel's reason: ${err}"
        warn "Containers will not start at all while this is the case, because Podman"
        warn "enables every controller this cgroup advertises, whether or not the"
        warn "container needs it."
        warn "Containers that need one of them fail to start with 'enabling controller"
        warn "<name>: ... cgroup.subtree_control: no such file or directory', which"
        warn "names the container's own cgroup rather than this one."
        warn "'Device or resource busy' means a process is still in the cgroup root;"
        warn "anything else usually means the Supervisor's Docker did not delegate the"
        warn "controller to this container in the first place, and Protection mode"
        warn "being on is the usual cause."
    elif [ "${#enabled[@]}" -eq 0 ]; then
        warn "No cgroup controllers could be delegated; containers will run but"
        warn "resource limits (--memory, --cpus) will not be enforced."
    fi
}

configure_procfs() {
    if procfs_net_is_writable; then
        return 0
    fi

    if mount -o remount,rw /proc/sys 2>/dev/null && procfs_net_is_writable; then
        log "Remounted /proc/sys read-write so netavark can configure container networking"
        return 0
    fi

    warn "/proc/sys is read-only and could not be remounted read-write."
    warn "Podman containers on a bridge network will fail to start with a"
    warn "'netavark: set sysctl ...: Read-only file system' error."
    warn "This needs Protection mode OFF. As a stop-gap, containers started with"
    warn "--network=host do not need netavark and are unaffected."
}

# Podman's bridges are created in the *host* network namespace, because this
# add-on runs with host networking. They therefore outlive the add-on: stopping
# it kills the containers but leaves the bridges behind on the host, and a run
# that failed halfway - as every run did before /proc/sys was remounted
# read-write - can leave a bridge without its gateway address. netavark then
# reuses that half-configured bridge instead of recreating it, and aardvark-dns
# cannot bind the gateway it expects:
#
#   Error starting server failed to bind udp listener on 10.89.0.1:53:
#   IO error: Cannot assign requested address (os error 99)
#
# Restarting the add-on does not clear this, which makes it look permanent. At
# startup none of our containers can be running - the Supervisor kills them
# together with the add-on - so any podmanN bridge still present is leftover
# state, and removing it lets netavark build a correct one on the next run.
cleanup_stale_podman_bridges() {
    command -v ip >/dev/null 2>&1 || return 0

    # Belt and braces: never touch anything while containers are running, even
    # though that should be impossible this early.
    if [ "$(podman ps --quiet 2>/dev/null | wc -l)" -gt 0 ]; then
        return 0
    fi

    local iface removed=()
    while read -r iface; do
        [ -n "${iface}" ] || continue
        if ip link delete "${iface}" 2>/dev/null; then
            removed+=("${iface}")
        fi
    done < <(
        ip -o link show type bridge 2>/dev/null \
            | awk -F': ' '{print $2}' | cut -d'@' -f1 \
            | grep -E '^podman[0-9]*$' || true
    )

    if [ "${#removed[@]}" -gt 0 ]; then
        log "Removed leftover Podman bridges from the host network namespace: ${removed[*]}"
        log "netavark will recreate them, with their gateway addresses, on first use."
    fi
}

# Published container ports and container egress both depend on the packets
# being *forwarded*, and on Home Assistant OS something else already owns that
# decision: the Supervisor's Docker sets the iptables FORWARD policy to DROP
# and accepts only what its own rules match. netavark cannot undo that. Since
# netavark 2.x its only firewall backends are firewalld and nftables, so its
# ACCEPT rules go into the "inet netavark" nftables table - a different table
# from Docker's "ip filter", and both are evaluated at the same netfilter hook.
# An ACCEPT in one does not overrule a DROP in the other, so the packet dies in
# Docker's chain no matter what netavark wrote.
#
# The symptom is a container that starts fine, is listed by `podman ps` with
# its port mapping, and is simply unreachable - with no error anywhere, because
# from Podman's point of view nothing failed.
#
# Docker's own escape hatch for this is the DOCKER-USER chain, which it jumps
# to first from FORWARD and never generates rules into itself. Accepting the
# podman bridges there is the documented way to let non-Docker traffic through.
# The rules are scoped to podman interfaces and nothing else.
#
# This writes to the *host's* firewall, which deserves saying out loud - but so
# does every bridge netavark creates here, for the same reason: the add-on runs
# in the host's network namespace. The rules are added only when the policy is
# actually DROP, and only when they are not already present.
docker_iptables_cmd() {
    local family="$1" cmd
    # iptables-nft and iptables-legacy maintain entirely separate rule sets and
    # cannot see each other's chains, so "which one shows DOCKER-USER" is a
    # direct answer to "which one is Docker using".
    for cmd in "${family}-nft" "${family}-legacy" "${family}"; do
        command -v "${cmd}" >/dev/null 2>&1 || continue
        if "${cmd}" -w 5 -S DOCKER-USER >/dev/null 2>&1; then
            printf '%s\n' "${cmd}"
            return 0
        fi
    done
    return 1
}

allow_podman_forwarding_family() {
    local family="$1"
    local cmd policy direction added=0

    cmd="$(docker_iptables_cmd "${family}")" || return 0

    policy="$("${cmd}" -w 5 -S FORWARD 2>/dev/null | awk '$1 == "-P" {print $3; exit}')"
    [ "${policy}" = "DROP" ] || return 0

    for direction in -i -o; do
        if "${cmd}" -w 5 -C DOCKER-USER "${direction}" "podman+" -j ACCEPT 2>/dev/null; then
            continue
        fi
        if "${cmd}" -w 5 -I DOCKER-USER 1 "${direction}" "podman+" -j ACCEPT 2>/dev/null; then
            added=1
        else
            warn "Could not add the ${family} DOCKER-USER rule for podman interfaces."
            warn "Published container ports will not be reachable from outside the add-on."
            return 0
        fi
    done

    if [ "${added}" = "1" ]; then
        log "Allowed forwarding for podman bridges in the host's DOCKER-USER chain (${cmd});"
        log "without it Docker's FORWARD policy of DROP silently blackholes published ports."
    fi
}

allow_podman_forwarding() {
    allow_podman_forwarding_family iptables
    allow_podman_forwarding_family ip6tables
}

# Turning on IPv6 forwarding has a side effect that costs the host its IPv6
# address if it is not handled: the kernel stops accepting Router
# Advertisements on an interface once forwarding is on, unless that interface's
# accept_ra is 2 rather than the default 1. On a normal LAN the host's IPv6
# address and default route come from RAs, so it would keep working until the
# current lease expired and then quietly lose IPv6 - the kind of failure that
# gets blamed on anything but a container runtime.
#
# Remember: this add-on shares the host's network namespace, so these are the
# host's interfaces, not ours. Only interfaces that are actually relying on RAs
# (accept_ra == 1) are touched, and each one is named in the log.
keep_accepting_router_advertisements() {
    local path iface changed=()

    for path in /proc/sys/net/ipv6/conf/*/accept_ra; do
        [ -w "${path}" ] || continue
        iface="${path%/accept_ra}"
        iface="${iface##*/}"
        case "${iface}" in
            all | default | lo) continue ;;
        esac
        [ "$(cat "${path}" 2>/dev/null)" = "1" ] || continue
        if printf '2\n' > "${path}" 2>/dev/null; then
            changed+=("${iface}")
        fi
    done

    if [ "${#changed[@]}" -gt 0 ]; then
        log "Set accept_ra=2 on ${changed[*]} so the host keeps its IPv6 address"
        log "and default route now that IPv6 forwarding is on."
    fi
}

# Forwarding has to be enabled at all, on top of being permitted. Docker turns
# it on for IPv4 when it starts, so this is normally already true; IPv6
# forwarding usually is not, and a dual-stack Podman network needs it - both
# for the containers' own traffic and for the DNAT of published ports.
enable_ip_forwarding() {
    local knob
    for knob in net.ipv4.ip_forward net.ipv6.conf.all.forwarding; do
        local path="/proc/sys/${knob//.//}"
        [ -r "${path}" ] || continue
        [ "$(cat "${path}")" = "0" ] || continue

        # Before, not after: between the two writes the host would be
        # forwarding while ignoring RAs.
        if [ "${knob}" = "net.ipv6.conf.all.forwarding" ]; then
            keep_accepting_router_advertisements
        fi

        if printf '1\n' > "${path}" 2>/dev/null; then
            log "Enabled ${knob} on the host, which container networking needs."
        else
            warn "${knob} is 0 and could not be set; container traffic will not be routed."
        fi
    done
}

# Podman's built-in default network is IPv4-only and cannot be made dual-stack:
# containers.conf can name the default network and give it a subnet, but that
# subnet "must be a valid IPv4 CIDR block" - there is no IPv6 equivalent, and
# the network podman creates for itself has no IPv6 address.
#
# That matters more here than it would elsewhere, because netavark only writes
# IPv6 DNAT rules for a container that has an IPv6 address (it checks
# container_ip_v6 before generating them) and Podman has no userland proxy to
# bridge the families the way Docker's docker-proxy does. So on the default
# network, `podman run -p 443:443` answers IPv4 clients and is simply invisible
# over IPv6 - with nothing in any log to say so.
#
# The fix is a network of our own, created dual-stack, named as the default in
# containers.conf. Containers already attached to the old network keep it until
# they are recreated.
ensure_dualstack_default_network() {
    if podman network exists "${PODMAN_DEFAULT_NETWORK}" 2>/dev/null; then
        return 0
    fi

    if podman network create --ipv6 "${PODMAN_DEFAULT_NETWORK}" >/dev/null 2>&1; then
        log "Created the dual-stack default network '${PODMAN_DEFAULT_NETWORK}';"
        log "containers now get an IPv6 address, so published ports answer over IPv6 too."
    else
        warn "Could not create the dual-stack network '${PODMAN_DEFAULT_NETWORK}'."
        warn "Containers will fall back to an IPv4-only network, and their published"
        warn "ports will not be reachable over IPv6. Try it by hand to see why:"
        warn "  podman network create --ipv6 ${PODMAN_DEFAULT_NETWORK}"
    fi
}

# An add-on's /config is the Supervisor directory app_configs/<slug>, and the
# slug depends on where the add-on was installed from: a local folder gives
# local_<name>, a repository gives <repository-hash>_<name>. Reinstalling from
# the other source is therefore a *different* add-on as far as the Supervisor is
# concerned - it gets an empty /config, while the old directory sits untouched
# next to it with every image, container and installed package in it.
#
# Nothing is lost, but it looks exactly like it: the shell comes up with no
# containers, no images and none of the packages that were installed. So when
# the storage is empty, the neighbouring directories are checked - all of them
# are mapped here at /app_configs - and what was found is named, along with how
# to take it back.
hint_at_orphaned_storage() {
    local graphroot="$1"
    local candidate found=()

    # Only worth saying when this really is a fresh start: podman's graph root
    # holds these once it has pulled anything at all.
    [ -d "${graphroot}/overlay-images" ] && return 0
    [ -d "${graphroot}/overlay-containers" ] && return 0
    [ -d /app_configs ] || return 0

    for candidate in /app_configs/*/podman /app_configs/*/system; do
        [ -d "${candidate}" ] || continue
        # Skip our own directory, whatever slug we happen to have.
        [ "${candidate}" -ef "${graphroot}" ] && continue
        [ "${candidate}" -ef "${PERSIST_DIR:-/config}/system" ] && continue
        [ -n "$(ls -A "${candidate}" 2>/dev/null)" ] || continue
        found+=("${candidate}")
    done

    [ "${#found[@]}" -gt 0 ] || return 0

    warn "This add-on's storage is empty, but another add-on directory still holds"
    warn "what looks like a previous installation of it:"
    local path
    for path in "${found[@]}"; do
        warn "  ${path}  ($(du -sh "${path}" 2>/dev/null | cut -f1))"
    done
    warn "That happens when the add-on is reinstalled from a different source - a"
    warn "local folder and a repository get different slugs, and the slug is the"
    warn "name of this directory - so the old data is intact under the old name."
    warn "To take it back, stop this add-on and move the directories over, e.g.:"
    warn "  mv /app_configs/<old-slug>/podman /app_configs/<this-slug>/podman"
    warn "  mv /app_configs/<old-slug>/system /app_configs/<this-slug>/system"
    warn "Move them rather than copying: the system layer must not exist twice."
}

warn_on_low_space() {
    local graphroot="$1"
    local avail_mb
    avail_mb="$(df -Pm "${graphroot}" 2>/dev/null | awk 'NR==2 {print $4}')" || return 0
    [ -n "${avail_mb}" ] || return 0
    if [ "${avail_mb}" -lt 2048 ]; then
        warn "Only ${avail_mb} MB free on ${graphroot}; container images will fill this up quickly."
    fi
}

configure_podman() {
    local graphroot="${PODMAN_STORAGE_PATH}"

    mkdir -p "${graphroot}" "${PODMAN_RUNROOT}" /run/libpod
    chmod 0700 "${graphroot}"

    assert_path_is_persistent "${graphroot}"
    hint_at_orphaned_storage "${graphroot}"
    configure_cgroups
    configure_procfs
    select_storage_driver "${graphroot}"
    write_storage_conf "${graphroot}"
    write_containers_conf "${graphroot}"
    write_registries_conf
    cleanup_stale_podman_bridges
    enable_ip_forwarding
    ensure_dualstack_default_network
    allow_podman_forwarding
    warn_on_low_space "${graphroot}"

    # Sanity check with the configuration we just wrote. Not fatal: podman can
    # be perfectly usable for some operations even if `info` trips over
    # something, and losing SSH access over it would leave nothing to debug
    # with. But say so loudly, because it usually means cgroup delegation or
    # the storage setup is wrong.
    local reported_driver
    if reported_driver="$(podman info --format '{{.Store.GraphDriverName}}' 2>/dev/null)"; then
        log "Podman is ready (graph driver: ${reported_driver}, root: ${graphroot})"
        if [ "${reported_driver}" = "vfs" ]; then
            warn "Podman reports the 'vfs' driver despite the configuration above."
            warn "Expect very slow pulls and heavy disk usage; check 'podman info' output."
        fi
    else
        warn "'podman info' failed. Podman may not work correctly in this environment."
        warn "Most likely causes: Protection mode is still ON for this add-on, or the"
        warn "kernel refuses the cgroup setup. Run 'podman info' over SSH for details."
    fi
}
