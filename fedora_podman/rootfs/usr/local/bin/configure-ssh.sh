#!/usr/bin/env bash
# SSH setup for the Fedora Podman Shell add-on.
# Sourced by entrypoint.sh; not meant to be executed on its own.

# Generates the host keys once and keeps them on the mapped config directory.
# If they lived in the image, every add-on update would hand out a new host
# fingerprint and every client would refuse to connect with a scary
# "REMOTE HOST IDENTIFICATION HAS CHANGED" until the user cleared known_hosts.
setup_host_keys() {
    mkdir -p "${SSH_KEY_DIR}"
    chmod 0700 "${SSH_KEY_DIR}"

    local key_type
    for key_type in ed25519 rsa; do
        local key_file="${SSH_KEY_DIR}/ssh_host_${key_type}_key"
        if [ ! -f "${key_file}" ]; then
            log "Generating persistent ${key_type} host key"
            # -N '' : host keys must be usable without a passphrase, there is
            # nobody to type one at start-up.
            if [ "${key_type}" = "rsa" ]; then
                ssh-keygen -q -t rsa -b 4096 -f "${key_file}" -N '' -C 'fedora-podman-addon'
            else
                ssh-keygen -q -t "${key_type}" -f "${key_file}" -N '' -C 'fedora-podman-addon'
            fi
        fi
        chmod 0600 "${key_file}"
        chmod 0644 "${key_file}.pub"
    done
}

setup_authorized_keys() {
    local ssh_dir="/root/.ssh"
    local auth_file="${ssh_dir}/authorized_keys"

    mkdir -p "${ssh_dir}"
    # sshd refuses to use an authorized_keys file that is group- or
    # world-writable, and silently falls back to rejecting the login.
    chmod 0700 "${ssh_dir}"

    # Rewritten from the options on every start, so removing a key from the
    # add-on configuration actually revokes access.
    jq -r '.authorized_keys[]' "${OPTIONS_FILE}" > "${auth_file}"
    chmod 0600 "${auth_file}"
    chown -R root:root "${ssh_dir}"

    local count
    count="$(wc -l < "${auth_file}")"
    log "Installed ${count} authorized SSH key(s) for root"
}

write_sshd_config() {
    # sshd's privilege separation directory. It must exist and must not be
    # writable by anyone but root, or sshd refuses to start.
    mkdir -p /var/empty/sshd
    chmod 0711 /var/empty/sshd

    # Root has no usable password (key auth only), but the account must not be
    # *locked* either: with UsePAM no, sshd rejects logins to an account whose
    # shadow entry starts with '!', even for public-key authentication.
    # '*' means "no password will ever match" without marking it locked.
    usermod -p '*' root

    cat > /etc/ssh/sshd_config <<EOF
# Generated by the Fedora Podman Shell add-on on every start.
# Edit the add-on options instead; changes made here are overwritten.

Port ${SSH_PORT}
AddressFamily any
ListenAddress 0.0.0.0
ListenAddress ::

HostKey ${SSH_KEY_DIR}/ssh_host_ed25519_key
HostKey ${SSH_KEY_DIR}/ssh_host_rsa_key

# Public-key authentication only. Every other method is turned off explicitly
# rather than left at its default, so a future OpenSSH default change cannot
# quietly open one of them up.
PubkeyAuthentication yes
AuthorizedKeysFile /root/.ssh/authorized_keys
PermitRootLogin prohibit-password
PasswordAuthentication no
PermitEmptyPasswords no
KbdInteractiveAuthentication no
GSSAPIAuthentication no
HostbasedAuthentication no
# PAM is not used: its default stack pulls in modules (pam_loginuid, systemd
# session registration) that have nothing to attach to in a container and only
# produce errors. With key-only auth it buys us nothing here.
UsePAM no

# The point of this add-on is a working shell, so forwarding is allowed: it is
# how you reach a container's port from your laptop without publishing it.
AllowTcpForwarding yes
AllowAgentForwarding yes
X11Forwarding no
PermitTTY yes
PrintMotd yes
AcceptEnv LANG LC_*

# Keeps sessions from being dropped by NAT/firewall idle timeouts.
ClientAliveInterval 60
ClientAliveCountMax 5

LogLevel INFO
PidFile /run/sshd.pid
Subsystem sftp /usr/libexec/openssh/sftp-server
EOF
    chmod 0600 /etc/ssh/sshd_config

    # Fail here rather than in the exec at the end of the entrypoint, where the
    # error would be the last line of a log nobody scrolls back through.
    if ! /usr/sbin/sshd -t -f /etc/ssh/sshd_config; then
        fatal \
            "The generated sshd configuration is invalid (see the error above)." \
            "This is a bug in the add-on unless you edited /etc/ssh/sshd_config by hand."
    fi
}

configure_ssh() {
    setup_host_keys
    setup_authorized_keys
    write_sshd_config

    # A login shell needs these; without a langpack-backed locale, tools that
    # print anything non-ASCII come out mangled.
    cat > /etc/profile.d/10-addon-shell.sh <<'EOF'
# Installed by the Fedora Podman Shell add-on.
export PATH="/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"
export LANG="${LANG:-en_US.UTF-8}"
export EDITOR="${EDITOR:-nano}"
EOF
}
